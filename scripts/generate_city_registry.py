"""Generate the TypeScript geography contract without runtime JSON-loader differences."""
import argparse
import json
from pathlib import Path
from city_registry import REGISTRY


def generated():
    payload = {key: REGISTRY[key] for key in ('version', 'cities', 'counties')}
    return ('// Generated by scripts/generate_city_registry.py. Edit config/cities.json.\n'
            'export const CITY_REGISTRY = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / 'lib/cities.generated.ts'
    content = generated()
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit('City registry output is stale; run python scripts/generate_city_registry.py')
    else:
        path.write_text(content, encoding='utf-8')
